"""Build a downloadable PDF from a generated glossary.

Uses PyMuPDF, which DocuMind already depends on, so no new package is needed.
The glossary text comes from the browser, so every value is validated, clipped
and HTML-escaped before it is laid out.
"""

import html
import io
from datetime import date
from uuid import UUID

import pymupdf

from backend.storage.document_store import get_document

VALID_VIEWS = {"simple", "technical", "both"}
VALID_SOURCE_TYPES = {"document", "ai_supplemented"}

MAX_EXPORT_TERMS = 300
MAX_EXPORT_PAGES = 50
MAX_TERM_LENGTH = 200
MAX_SIMPLE_LENGTH = 2000
MAX_TECHNICAL_LENGTH = 4000

PDF_CSS = """
body { font-family: sans-serif; font-size: 10pt; color: #1f1d33; }
h1 { font-size: 20pt; color: #5b43d0; margin: 0 0 4pt 0; }
h2 { font-size: 13pt; color: #5b43d0; margin: 14pt 0 4pt 0; border-bottom: 1px solid #c9bff7; }
p { margin: 0 0 3pt 0; }
p.sub { font-size: 9pt; color: #5a5873; margin: 0 0 10pt 0; }
p.term { font-size: 11pt; font-weight: bold; margin: 8pt 0 2pt 0; }
p.label { font-size: 8pt; color: #5b43d0; font-weight: bold; margin: 3pt 0 0 0; }
p.meta { font-size: 8.5pt; color: #625f7a; margin: 2pt 0 4pt 0; }
p.note { font-size: 8.5pt; color: #625f7a; margin: 14pt 0 0 0; }
"""


def _text(value, limit: int) -> str:
    if not isinstance(value, str):
        return ""

    return " ".join(value.split())[:limit]


def _clean_terms(terms) -> list[dict]:
    if not isinstance(terms, list) or not terms:
        raise ValueError("There is no glossary to export.")

    if len(terms) > MAX_EXPORT_TERMS:
        raise ValueError("This glossary is too large to export.")

    cleaned = []

    for item in terms:
        if not isinstance(item, dict):
            continue

        term = _text(item.get("term"), MAX_TERM_LENGTH)
        simple = _text(item.get("simple_definition"), MAX_SIMPLE_LENGTH)

        if not term or not simple:
            continue

        raw_pages = item.get("pages")
        pages = sorted({
            page for page in (raw_pages if isinstance(raw_pages, list) else [])
            if isinstance(page, int) and not isinstance(page, bool) and page >= 1
        })[:MAX_EXPORT_PAGES]

        source_type = item.get("source_type")

        cleaned.append({
            "term": term,
            "simple": simple,
            "technical": _text(item.get("technical_definition"), MAX_TECHNICAL_LENGTH),
            "pages": pages,
            "source_type": source_type if source_type in VALID_SOURCE_TYPES else "ai_supplemented",
        })

    if not cleaned:
        raise ValueError("There is no valid glossary content to export.")

    cleaned.sort(key=lambda entry: entry["term"].casefold())

    return cleaned


def _letter_of(term: str) -> str:
    first = term[:1].upper()
    return first if first.isalpha() else "#"


def _build_html(filename: str, terms: list[dict], view: str) -> str:
    def escape(value):
        # Quotes stay as they are: only & < > need escaping in element text.
        return html.escape(value, quote=False)

    parts = [
        "<h1>Glossary</h1>",
        f'<p class="sub">{escape(filename)} | {len(terms)} terms | '
        f"generated by DocuMind on {date.today().strftime('%d %b %Y')}</p>",
    ]

    current_letter = None

    for entry in terms:
        letter = _letter_of(entry["term"])

        if letter != current_letter:
            current_letter = letter
            parts.append(f"<h2>{escape(letter)}</h2>")

        parts.append(f'<p class="term">{escape(entry["term"])}</p>')

        technical = entry["technical"]

        if view == "technical":
            # Fall back to the simple text so no entry is ever left blank.
            parts.append(f'<p>{escape(technical or entry["simple"])}</p>')
        elif view == "simple" or not technical:
            parts.append(f'<p>{escape(entry["simple"])}</p>')
        else:
            parts.append('<p class="label">SIMPLE</p>')
            parts.append(f'<p>{escape(entry["simple"])}</p>')
            parts.append('<p class="label">TECHNICAL</p>')
            parts.append(f"<p>{escape(technical)}</p>")

        meta = []

        if entry["pages"]:
            label = "Page" if len(entry["pages"]) == 1 else "Pages"
            meta.append(f"{label} {', '.join(str(page) for page in entry['pages'])}")

        meta.append(
            "Supported by the document"
            if entry["source_type"] == "document"
            else "AI-supplemented (not fully explained in the document)"
        )

        parts.append(f'<p class="meta">{escape(" | ".join(meta))}</p>')

    parts.append(
        '<p class="note">Definitions marked AI-supplemented use general AI knowledge '
        "because the document does not explain the term sufficiently. "
        "Verify important information.</p>"
    )

    return "".join(parts)


def build_glossary_pdf(document_id: str, terms, view: str = "both") -> bytes:
    """Return the glossary of an existing document as PDF bytes."""

    if not isinstance(document_id, str) or not document_id.strip():
        raise ValueError("Please select a PDF document.")

    try:
        UUID(document_id)
    except (ValueError, AttributeError):
        raise ValueError("Invalid document ID.") from None

    if view not in VALID_VIEWS:
        raise ValueError("View must be simple, technical, or both.")

    document = get_document(document_id)

    if document is None:
        raise FileNotFoundError("The selected document was not found.")

    entries = _clean_terms(terms)
    content = _build_html(document.get("filename", "Uploaded PDF"), entries, view)

    buffer = io.BytesIO()
    writer = pymupdf.DocumentWriter(buffer)
    story = pymupdf.Story(html=content, user_css=PDF_CSS)

    page_rect = pymupdf.paper_rect("a4")
    content_rect = page_rect + (50, 50, -50, -50)

    more = True

    while more:
        device = writer.begin_page(page_rect)
        more, _ = story.place(content_rect)
        story.draw(device)
        writer.end_page()

    writer.close()

    return buffer.getvalue()
